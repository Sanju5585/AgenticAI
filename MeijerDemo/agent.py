#"Supports price queries: 'smartwatches under 80', 'tablets between 50 and 100 pounds', 'smartphones over 60 dollars'."
def is_direct_product_query(query: str) -> bool:
    """
    Check if query is a direct product search (e.g., 'frozen meals', 'snacks', 'beverages')
    """
    query_lower = query.lower().strip()
    
    # Direct product terms
    direct_products = [
        'chips', 'crackers', 'cookies', 'snacks', 'pizza', 'frozen', 'ice cream',
        'bread', 'cake', 'bakery', 'soda', 'coffee', 'water', 'milk', 'yogurt',
        'cheese', 'cereal', 'granola', 'frozen meal', 'pot pie', 'dairy'
    ]
    
    # Remove common search prefixes
    clean_query = query_lower.replace('show me', '').replace('find', '').replace('search for', '').replace('get', '').strip()
    
    # Check if the cleaned query is just a product name
    return clean_query in direct_products or any(clean_query == product for product in direct_products)

