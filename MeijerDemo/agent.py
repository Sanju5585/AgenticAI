def extract_price_constraints_ai(query: str) -> tuple:
    """
    Use AI to extract price constraints from natural language
    """
    try:
        price_prompt = f"""
        Extract price constraints from this query: "{query}"
        
        Analyze the query for any price, budget, or cost-related information in any language.
        Look for patterns indicating price ranges, maximum prices, minimum prices, or budget constraints.
        
        If there are price constraints, return in format:
        "MIN:value MAX:value" (e.g., "MIN:50 MAX:200")
        
        If no price constraints are found, return: "NONE"
        
        Consider terms like: under, over, below, above, between, budget, cheap, expensive, premium, affordable, cost, price, maximum, minimum, range, etc.
        Also consider currency symbols and numbers in any language context.
        
        Price constraint:
        """
        
        response = llm.invoke(price_prompt)
        constraint = response.content.strip()
        
        if constraint == "NONE":
            return "", []
        
        conditions = []
        params = []
        
        if "MIN:" in constraint:
            min_val = constraint.split("MIN:")[1].split()[0]
            try:
                conditions.append(" AND PRICE >= ?")
                params.append(float(min_val))
            except ValueError:
                pass
                
        if "MAX:" in constraint:
            max_val = constraint.split("MAX:")[1].split()[0]
            try:
                conditions.append(" AND PRICE <= ?")
                params.append(float(max_val))
            except ValueError:
                pass
        
        return "".join(conditions), params
        
    except Exception as e:
        print(f"Price extraction failed: {e}")
        return "", []


