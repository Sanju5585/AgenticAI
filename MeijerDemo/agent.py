        sql = '''
            SELECT p.PRODUCT_ID, p.PRODUCT_NAME, p.SUMMARY, p.PRICE, p.CATEGORY_IDS, p.IMAGE_URL,
                   c.CATEGORY_NAME
            FROM SAP_MEIJER_PRODUCTS_V1 p
            LEFT JOIN SAP_MEIJER_CATEGORY_V1 c ON p.CATEGORY_IDS LIKE '%' || c.CATEGORY_ID || '%'
            WHERE TRIM(p.PRODUCT_ID) = ?
        '''
        
        print(f"DEBUG: Executing product details SQL: {sql}")
        cursor.execute(sql, (product_id,))
        rows = cursor.fetchall()
        
        if not rows:
            cursor.close()
            conn.close()
            return {"error": f"Product {product_id} not found"}
        
        # Process the results
        product_info = rows[0]  # Get the first row for main product info
        categories = [row[6] for row in rows if row[6]]  # Collect all category names
        
        result = {
            'PRODUCT_ID': product_info[0],
            'PRODUCT_NAME': product_info[1],
            'SUMMARY': product_info[2],
            'PRICE': float(product_info[3]) if product_info[3] else 0.0,
            'CATEGORY_IDS': product_info[4],
            'IMAGE_URL': product_info[5],
            'CATEGORIES': list(set(categories)) if categories else []  # Remove duplicates
        }
        
        cursor.close()
        conn.close()
        
        print(f"DEBUG: Product details result: {result}")
        return {"results": [result]}
        
