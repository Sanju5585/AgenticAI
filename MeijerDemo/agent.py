def detect_order_query_with_ai(query: str) -> bool:
    """
    🤖 AI-driven order query detection that precisely identifies when a user is asking about their orders
    vs when they're asking for product searches.
    
    This prevents false positives where product searches like "show tablets" get misclassified as order queries.
    """
    try:
        order_detection_prompt = f"""
        You are an AI system that determines if a user query is asking about ORDERS/ORDER HISTORY vs PRODUCT SEARCHES.

        Query: "{query}"

        CONTEXT: This is an e-commerce website where users can:
        1. Search for products (smartphones, tablets, smartwatches, etc.)
        2. View their personal order history

        CRITICAL DISTINCTION:
        - ORDER QUERIES: User wants to see their personal purchase history, order status, past orders
        - PRODUCT QUERIES: User wants to browse/search for products to potentially buy

        EXAMPLES OF ORDER QUERIES (return true):
        - "show my orders"
        - "my order history" 
        - "view my orders"
        - "check my order status"
        - "what are my orders"
        - "list my orders"
        - "order history"
        - "my past orders"

        EXAMPLES OF PRODUCT QUERIES (return false):
        - "show frozen meals" (searching for frozen products)
        - "show me snacks" (searching for snack products)
        - "find beverages" (product search)
        - "show bakery items" (product search)
        - "display ice cream" (product search)
        - "I want to see the dairy products" (product search)
        - "show me cereals" (product search)
        - "any offers" (promotion search)
        - "show chips" (product search)
        
        EXAMPLES OF CART QUERIES (return false):
        - "show my cart" (NOT an order query - this is cart viewing)
        - "view cart" (cart query, not order)
        - "my cart" (cart query, not order)
        - "what's in my cart" (cart query, not order)

        RULES:
        1. Only return true if the user is EXPLICITLY asking about their personal order history
        2. Product search queries should ALWAYS return false, even if they use words like "show"
        3. CART queries should ALWAYS return false - "show my cart" is NOT an order query!
        4. Look for possessive pronouns (my, mine) with "orders" or "order history"
        5. Generic product searches are NOT order queries
        6. Cart queries are NOT order queries!

        Return ONLY: true or false
        """
        
        response = llm.invoke(order_detection_prompt)
        result = response.content.strip().lower()
        
        is_order = result == 'true'
        print(f"🤖 AI Order Detection: '{query}' → {is_order} (AI response: '{result}')")
        return is_order
        
    except Exception as e:
        print(f"❌ AI order detection failed: {e}")
        # Fallback to very conservative detection - only clear order queries
        conservative_order_keywords = ['my orders', 'my order', 'order history', 'order status']
        is_order = any(keyword in query.lower() for keyword in conservative_order_keywords)
        print(f"🔄 Fallback order detection: '{query}' → {is_order}")
        return is_order

