        # Base query structure - V2 table with DECIMAL price
        base_sql = """
            SELECT TOP 5 PRODUCT_ID, PRODUCT_NAME, SUMMARY, PRICE, CATEGORY_IDS, IMAGE_URL
            FROM SAP_MEIJER_PRODUCTS_V1
            WHERE 1=1
        """
        
        conditions = []
        params = []
        
